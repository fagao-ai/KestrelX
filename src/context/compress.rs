use std::sync::Arc;

use async_trait::async_trait;

use crate::{Message, Result, TokenCounter};

/// Input to a context compressor.
#[derive(Clone)]
pub struct CompressionRequest {
    /// Conversation messages, excluding temporary system prompt messages.
    pub messages: Vec<Message>,
    /// Maximum tokens available for conversation history.
    pub budget_tokens: usize,
    /// Token estimator selected by the agent.
    pub token_counter: Arc<dyn TokenCounter>,
}

impl std::fmt::Debug for CompressionRequest {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("CompressionRequest")
            .field("message_count", &self.messages.len())
            .field("budget_tokens", &self.budget_tokens)
            .finish_non_exhaustive()
    }
}

/// Result of one compression operation.
#[derive(Debug, Clone)]
pub struct Compression {
    /// Replacement conversation history.
    pub messages: Vec<Message>,
    /// Number of original messages removed.
    pub removed_messages: usize,
    /// Summary or omission marker inserted at the front.
    pub summary: Option<String>,
    /// Whether the summary was generated by a model.
    pub summarized: bool,
    /// Estimated tokens before compression.
    pub before_tokens: usize,
    /// Estimated tokens after compression.
    pub after_tokens: usize,
}

/// Reduces conversation history to fit a token budget.
///
/// Implementations must preserve assistant tool calls together with their tool
/// results. Provider APIs reject histories that split those pairs.
#[async_trait]
pub trait ContextCompressor: Send + Sync {
    /// Preferred maximum input budget.
    ///
    /// The agent uses the smaller of this value and the declared model context
    /// window (after reserving output tokens).
    fn max_input_tokens(&self) -> Option<usize> {
        None
    }

    /// Compresses history to approximately `request.budget_tokens`.
    async fn compress(&self, request: CompressionRequest) -> Result<Compression>;
}

impl std::fmt::Debug for dyn ContextCompressor {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("ContextCompressor")
            .field("max_input_tokens", &self.max_input_tokens())
            .finish_non_exhaustive()
    }
}

pub(crate) struct Split {
    pub kept: Vec<Message>,
    pub removed_messages: usize,
    pub kept_tokens: usize,
}

pub(crate) fn split_to_budget(
    messages: &[Message],
    budget: usize,
    counter: &dyn TokenCounter,
) -> Split {
    let total_tokens = counter.count_messages(messages);
    if total_tokens <= budget || messages.is_empty() {
        return Split {
            kept: messages.to_vec(),
            removed_messages: 0,
            kept_tokens: total_tokens,
        };
    }

    let units = atomic_units(messages);
    let mut start = messages.len();
    let mut kept_tokens = 0usize;

    for (unit_start, unit_end) in units.iter().rev() {
        let unit_tokens = counter.count_messages(&messages[*unit_start..*unit_end]);
        if kept_tokens.saturating_add(unit_tokens) > budget && start != messages.len() {
            break;
        }
        kept_tokens += unit_tokens;
        start = *unit_start;
    }

    Split {
        kept: messages[start..].to_vec(),
        removed_messages: start,
        kept_tokens,
    }
}

/// Groups assistant tool calls and all immediately following tool messages so
/// that compaction never separates a call from its result.
fn atomic_units(messages: &[Message]) -> Vec<(usize, usize)> {
    let mut units = Vec::new();
    let mut index = 0;

    while index < messages.len() {
        let starts_tool_group = messages[index].role == crate::Role::Tool
            || (messages[index].role == crate::Role::Assistant
                && !messages[index].tool_calls.is_empty());
        let mut end = index + 1;
        if starts_tool_group {
            while end < messages.len() && messages[end].role == crate::Role::Tool {
                end += 1;
            }
        }
        units.push((index, end));
        index = end;
    }

    units
}

pub(crate) fn omission_marker(removed: usize) -> String {
    format!(
        "[Context compacted: {removed} earlier conversation messages were omitted to fit the context window.]"
    )
}

pub(crate) fn summary_message(summary: &str) -> Message {
    Message::system(format!(
        "[Conversation summary: earlier turns were compacted. Treat this as prior context.]\n{summary}"
    ))
}

pub(crate) fn truncate_text_to_tokens(
    text: &str,
    max_tokens: usize,
    counter: &dyn TokenCounter,
) -> String {
    if counter.count_text(text) <= max_tokens {
        return text.to_owned();
    }

    let mut boundaries = text
        .char_indices()
        .map(|(index, _)| index)
        .collect::<Vec<_>>();
    boundaries.push(text.len());
    let mut low = 0usize;
    let mut high = boundaries.len().saturating_sub(1);
    let mut best = 0usize;

    while low <= high {
        let middle = (low + high) / 2;
        let end = boundaries[middle];
        if counter.count_text(&text[..end]) <= max_tokens {
            best = end;
            low = middle + 1;
        } else if middle == 0 {
            break;
        } else {
            high = middle - 1;
        }
    }

    text[..best].trim_end().to_owned()
}

pub(crate) fn render_for_summary(messages: &[Message]) -> String {
    let mut output = String::new();
    for message in messages {
        output.push_str(match message.role {
            crate::Role::System => "[system]\n",
            crate::Role::User => "[user]\n",
            crate::Role::Assistant => "[assistant]\n",
            crate::Role::Tool => "[tool]\n",
        });
        let text = message.text();
        if !text.is_empty() {
            output.push_str(&text);
            output.push('\n');
        }
        for call in &message.tool_calls {
            output.push_str(&format!(
                "[tool call {}: {} {}]\n",
                call.id, call.name, call.arguments
            ));
        }
        if let Some(id) = &message.tool_call_id {
            output.push_str(&format!("[tool call id: {id}]\n"));
        }
        output.push('\n');
    }
    output
}
